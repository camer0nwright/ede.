/** The form video's id for an exercise (by name or alias), if it has one. */
export function formVideo(name: string): string | undefined {
  const info = findExercise(name);
  return info && FORM_VIDEOS[info.name];
}

/** The privacy-enhanced embed address for a video, started straight away. */
export const embedUrl = (id: string) => `https://www.youtube-nocookie.com/embed/${id}?autoplay=1&rel=0&playsinline=1`;
